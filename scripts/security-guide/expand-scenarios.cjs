function main() {
  const current = JSON.parse(fs.readFileSync(outPath, 'utf8'));
  const byId = new Map((current.scenarios || []).map((s) => [s.id, s]));
  let added = 0;
  for (const s of EXTRA) {
    if (byId.has(s.id)) {
      byId.set(s.id, { ...byId.get(s.id), ...s });
    } else {
      byId.set(s.id, s);
      added += 1;
    }
  }
  const scenarios = [...byId.values()].sort((a, b) =>
    String(a.id).localeCompare(String(b.id)),
  );
  const next = { version: 1, scenarios };
  fs.writeFileSync(outPath, `${JSON.stringify(next, null, 2)}\n`, 'utf8');
  console.log(
    `[scenarios:expand] total=${scenarios.length} added=${added} path=${path.relative(root, outPath)}`,
  );
}

main();
